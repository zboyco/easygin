func apiFile(path, content string) projectFile {
	return textFile("cmd/__PROJECT__/apis/"+path, content)
}

func lines(parts ...string) string {
	return strings.Join(parts, "\n") + "\n"
}

func tag(value string) string {
	return "`" + value + "`"
}

