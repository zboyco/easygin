func mustAuthTemplate() string {
	return lines(
		"package middleware",
		"",
		"import (",
		`	"context"`,
		"",
		`	"github.com/zboyco/easygin"`,
		")",
		"",
		"type mustAuthContextKey int",
		"",
		"type MustAuth struct {",
		`	Authorization string `+tag(`in:"header" name:"Authorization,omitempty" desc:"Bearer access token"`),
		`	AccessToken   string `+tag(`in:"query" name:"access_token,omitempty" desc:"Access token in query"`),
		"}",
		"",
		"type UserInfo struct {",
		`	ID   int64  `+tag(`json:"id"`),
		`	Name string `+tag(`json:"name"`),
		"}",
		"",
		`var ErrNotLogin = easygin.NewError(401, "用户未登录", "require authorization in header or query")`,
		"",
		"func (req *MustAuth) Output(ctx context.Context) (any, error) {",
		`	token := req.Authorization`,
		`	if token == "" {`,
		`		token = req.AccessToken`,
		`	}`,
		`	if token == "" {`,
		`		return nil, ErrNotLogin`,
		`	}`,
		"",
		`	return &UserInfo{`,
		`		ID:   1,`,
		`		Name: "easygin-admin",`,
		`	}, nil`,
		"}",
		"",
		"func (MustAuth) ContextKey() any {",
		"	return mustAuthContextKey(0)",
		"}",
		"",
		"func FromContext(ctx context.Context) *UserInfo {",
		"	if v := ctx.Value(mustAuthContextKey(0)); v != nil {",
		"		if user, ok := v.(*UserInfo); ok {",
		"			return user",
		"		}",
		"	}",
		"	return nil",
		"}",
	)
}

